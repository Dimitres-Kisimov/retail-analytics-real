def test_returned_totals_are_consistent(cleaned, result):
    # overview returned value == -sum of the signed returns revenue == sum over the per-SKU table
    signed = float(cleaned.returns["Revenue"].sum())
    assert result.overview["returned_value"] == pytest.approx(-signed)
    assert result.by_sku["returned_value"].sum() == pytest.approx(result.overview["returned_value"])
    assert result.overview["returned_units"] == int(-cleaned.returns["Quantity"].sum())
    # net == gross - returned, exactly
    o = result.overview
    assert o["net_value"] == pytest.approx(o["gross_value"] - o["returned_value"])


def test_by_sku_is_sorted_and_non_negative(result):
    bysku = result.by_sku
    assert (bysku["returned_value"] >= 0).all()
    assert (bysku["returned_units"] >= 0).all()
    assert bysku["returned_value"].is_monotonic_decreasing        # biggest returns first
    # a rate is only defined where the SKU was actually sold; where defined it is >= 0
    defined = bysku["value_return_rate"].notna()
    assert (bysku.loc[defined, "value_return_rate"] >= 0).all()
    assert (bysku.loc[bysku["sold_units"] > 0, "unit_return_rate"].notna()).all()


def test_match_shares_are_bounded(result):
    m = result.match
    assert 0 <= m["matched_lines"] <= m["identified_lines"] <= m["return_lines"]
    assert 0.0 <= m["matched_line_share"] <= 1.0
    assert 0.0 <= m["matched_value_share"] <= 1.0
    if m["matched_lines"]:
        assert m["p25_lag_days"] <= m["median_lag_days"] <= m["p75_lag_days"]
        assert m["median_lag_days"] >= 0.0


def test_lag_buckets_account_for_every_matched_line(result):
    lag = result.lag
    assert list(lag["lag_bucket"]) == [b[0] for b in returns.LAG_BUCKETS]
    assert int(lag["lines"].sum()) == result.match["matched_lines"]
    assert (lag["returned_value"] >= 0).all()
    share = lag["line_share"].sum()
    assert share == pytest.approx(1.0 if result.match["matched_lines"] else 0.0)


def test_monthly_net_is_gross_minus_returned(result):
    mon = result.monthly
    assert {"YearMonth", "gross", "returned", "net", "value_return_rate"} <= set(mon.columns)
    assert np.allclose(mon["net"], mon["gross"] - mon["returned"])
    assert (mon["returned"] >= 0).all()


def test_by_country_rate_is_returned_over_sold(result):
    bc = result.by_country
    assert bc["sold_value"].is_monotonic_decreasing        # top countries by gross first
    assert np.allclose(bc["value_return_rate"], bc["returned_value"] / bc["sold_value"])


def test_concentration_is_a_share(result):
    c = result.concentration
    assert 0.0 <= c["top_n_share"] <= 1.0
    assert c["n_returned_skus"] == len(result.by_sku)
    assert c["skus_to_80pct"] >= 1
    assert c["skus_to_80pct"] <= c["n_returned_skus"]


def test_headline_reports_measured_numbers(result):
    text = returns.headline_text(result)
    assert "returns run at" in text
    assert f"{100 * result.overview['value_return_rate']:.2f}%" in text


