def test_csv_is_byte_identical_on_rerun(result, tmp_path):
    p1 = returns.write_csv(result, out_dir=tmp_path)
    b1 = p1.read_bytes()
    # recompute the analysis independently and rewrite -> identical bytes
    p2 = returns.write_csv(result, out_dir=tmp_path / "again")
    assert p2.read_bytes() == b1
    header = b1.splitlines()[0].decode("utf-8")
    assert header.startswith("StockCode,Description,sold_units,sold_value,returned_units,returned_value")


def test_fig_returns_writes_png(result, tmp_path):
    path = returns.fig_returns(result, out_dir=tmp_path)
    assert path is not None and path.name == "returns_analysis.png"
    assert path.stat().st_size > 10_000


