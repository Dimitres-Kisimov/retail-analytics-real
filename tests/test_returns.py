"""Returns & cancellations analysis: hand-checked matching, invariants, determinism.

Runs on the shared 1,950-row real fixture plus tiny hand-built frames whose every
number is verifiable with pencil and paper. The fixture is a sparse random sample,
so dataset-specific *magnitudes* are not asserted here -- only the invariants that
must hold for any input, one fully hand-checked matching case, and the determinism
of the CSV deliverable. (Like the cohort tests, there is no full-dataset test here:
the measured full-data headline is reported in the README and regenerated by
`python -m retail --returns`.)
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from retail import clean, exports, ingest, paths, returns
from retail.__main__ import main


# --------------------------------------------------------------------------- #
# Hand-built cases (verifiable with pencil and paper)
# --------------------------------------------------------------------------- #
def _mk(rows) -> pd.DataFrame:
    cols = ["Invoice", "StockCode", "Description", "Quantity", "InvoiceDate", "Price", "CustomerID", "Country"]
    df = pd.DataFrame(rows, columns=cols)
    df["Invoice"] = df["Invoice"].astype(str)
    df["StockCode"] = df["StockCode"].astype(str)
    df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"])
    df["CustomerID"] = df["CustomerID"].astype("Int64")
    return df


def _hand_case() -> clean.CleanResult:
    # Codes are AA/BB/CC on purpose: single letters like B/D/M/S are reserved
    # bookkeeping codes that the cleaning pipeline strips as non-merchandise.
    rows = [
        # customer 1 buys AA twice, then returns AA -> matches the LATER sale (backward as-of)
        ("100", "AA", "Widget AA", 5, "2011-01-01 09:00", 2.0, 1, "UK"),
        ("101", "AA", "Widget AA", 5, "2011-01-05 09:00", 2.0, 1, "UK"),
        ("C900", "AA", "Widget AA", -5, "2011-01-10 09:00", 2.0, 1, "UK"),   # matched, lag 5 days, value 10
        # customer 1 buys BB but returns CC (never bought) -> identified, unmatched
        ("102", "BB", "Widget BB", 3, "2011-02-01 09:00", 4.0, 1, "UK"),
        ("C901", "CC", "Widget CC", -1, "2011-02-15 09:00", 9.0, 1, "UK"),   # unmatched, value 9
        # customer 2 returns AA with no prior sale -> identified, unmatched, value 4
        ("C902", "AA", "Widget AA", -2, "2011-03-01 09:00", 2.0, 2, "UK"),
        # unidentified return (no CustomerID) -> value 2, never matched
        ("C903", "AA", "Widget AA", -1, "2011-03-05 09:00", 2.0, pd.NA, "UK"),
    ]
    return clean.clean(_mk(rows))


def test_overview_is_hand_checkable():
    c = _hand_case()
    o = returns.returns_overview(c.sales, c.returns)
    # sales: 5*2 + 5*2 + 3*4 = 32 ; returns: 5*2 + 1*9 + 2*2 + 1*2 = 25
    assert o["gross_value"] == pytest.approx(32.0)
    assert o["returned_value"] == pytest.approx(25.0)
    assert o["net_value"] == pytest.approx(7.0)
    assert o["value_return_rate"] == pytest.approx(25.0 / 32.0)
    assert o["return_lines"] == 4
    assert o["cancellation_invoices"] == 4   # C900, C901, C902, C903 are distinct


def test_matching_is_hand_checkable():
    c = _hand_case()
    matched, stats = returns.match_returns_to_sales(c.sales, c.returns)
    assert stats["return_lines"] == 4
    assert stats["identified_lines"] == 3          # C903 has no CustomerID
    assert stats["matched_lines"] == 1             # only customer 1's A-return finds a prior A sale
    assert stats["matched_line_share"] == pytest.approx(0.25)
    assert stats["matched_value_share"] == pytest.approx(0.40)   # 10 of 25
    assert stats["median_lag_days"] == pytest.approx(5.0)        # to the 2011-01-05 sale, not 01-01
    # the matched row is the A return, attributed to the most recent prior sale
    row = matched.iloc[0]
    assert row["StockCode"] == "AA"
    assert row["days_to_return"] == 5.0
    assert row["SaleDate"] == pd.Timestamp("2011-01-05 09:00")


def test_empty_returns_is_handled(cleaned):
    empty = cleaned.returns.iloc[0:0]
    result = returns.run_returns_analysis(cleaned.sales, empty)
    assert result.overview["returned_value"] == 0.0
    assert result.overview["value_return_rate"] == 0.0
    assert result.by_sku.empty
    assert result.match["matched_lines"] == 0
    assert result.concentration["n_returned_skus"] == 0
    assert returns.fig_returns(result) is None       # nothing to plot


